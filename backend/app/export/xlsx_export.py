"""Fill an XLSX quotation template with openpyxl.

Cells keep their styles. Whole-cell numeric placeholders ({{subtotal}}, {{tax_amount}}, {{total}}) and
item quantities/prices/amounts are written as numbers so the template's number formats apply.
Known openpyxl limits (documented): images/charts may not survive, and when rows have to be inserted,
formulas below the insertion point are not adjusted.
"""

from __future__ import annotations

from copy import copy
from pathlib import Path

from openpyxl import load_workbook
from openpyxl.utils import column_index_from_string

from ..errors import AppError
from ..template_analysis import PLACEHOLDER_RE
from .common import Resolver


def _write_placeholders(ws, resolver: Resolver) -> None:
    for row in ws.iter_rows():
        for cell in row:
            if not isinstance(cell.value, str) or "{{" not in cell.value:
                continue
            text = cell.value
            whole = PLACEHOLDER_RE.fullmatch(text.strip())
            if whole:
                fid = f"ph:{whole.group(1).strip().lower()}"
                number = resolver.numeric_value(fid)
                if number is not None:
                    cell.value = number
                    continue

            def _sub(m) -> str:
                value = resolver.placeholder_text(m.group(1))
                return m.group(0) if value is None else value

            cell.value = PLACEHOLDER_RE.sub(_sub, text)


def export_xlsx(template_path: Path, out_path: Path, resolver: Resolver, draft: bool) -> list[str]:
    warnings: list[str] = []
    try:
        wb = load_workbook(str(template_path))
    except Exception as exc:
        raise AppError("export_failed", "The template could not be opened for export.", 500) from exc

    for ws in wb.worksheets:
        _write_placeholders(ws, resolver)

    for tf in resolver.template.fields:
        if tf.kind != "label_blank" or not tf.id.startswith("lbl:") or "!" not in tf.id:
            continue
        sheet_name, ref = tf.id[4:].split("!", 1)
        if sheet_name in wb.sheetnames:
            value = resolver.field_text(tf.id)
            if value:
                wb[sheet_name][ref] = value

    info = resolver.template.items_table
    if info is not None and info.sheet in wb.sheetnames:
        ws = wb[info.sheet]
        start = info.template_row
        col_attrs = resolver.column_attributes()
        max_col = max([c.index for c in info.columns] + [0]) + 1
        # Capacity: empty rows below the header until the next row with any content.
        capacity = 0
        r = start
        while r <= ws.max_row + 1 and capacity < 1000:
            if any(ws.cell(row=r, column=c).value not in (None, "") for c in range(1, max_col + 1)):
                break
            capacity += 1
            r += 1
        needed = len(resolver.q.line_items)
        if needed > capacity:
            extra = needed - capacity
            ws.insert_rows(start + capacity, amount=extra)
            for new_r in range(start + capacity, start + capacity + extra):
                for c in range(1, max_col + 1):
                    src = ws.cell(row=start, column=c)
                    dst = ws.cell(row=new_r, column=c)
                    if src.has_style:
                        dst._style = copy(src._style)
            warnings.append(
                f"Inserted {extra} row(s) into the items table. Formulas below row {start + capacity} may need review."
            )
        for i, item in enumerate(resolver.q.line_items):
            row_no = start + i
            for col_index, attr in col_attrs.items():
                cell = ws.cell(row=row_no, column=col_index + 1)
                if attr == "quantity" and item.quantity is not None:
                    cell.value = item.quantity
                elif attr == "unit_price" and item.unit_price is not None:
                    cell.value = item.unit_price
                elif attr == "amount" and item.amount is not None:
                    cell.value = item.amount
                else:
                    cell.value = resolver.item_text(item, attr)
    elif resolver.q.line_items:
        warnings.append("The template has no items table, so line items were not written into the workbook.")

    if draft:
        for ws in wb.worksheets:
            ws.oddHeader.center.text = "DRAFT - TenderFlow internal review. Not for submission."
    wb.properties.description = "Generated by TenderFlow" + (" (draft)" if draft else "")
    out_path.parent.mkdir(parents=True, exist_ok=True)
    wb.save(str(out_path))
    wb.close()
    return warnings


def xlsx_text(path: Path) -> str:
    wb = load_workbook(str(path), read_only=True, data_only=False)
    parts: list[str] = []
    try:
        for ws in wb.worksheets:
            for row in ws.iter_rows(values_only=True):
                parts.extend(str(v) for v in row if v is not None)
    finally:
        wb.close()
    return "\n".join(parts)


