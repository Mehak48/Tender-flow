"""Fill a DOCX quotation template (pipeline stage 9).

The uploaded template is never modified: it is opened from its stored copy and saved to a new path.
Formatting is preserved by writing replacement text into the existing runs (placeholders that span
several runs are merged into the first run of the span) and by cloning the items-table row for each
line item.
"""

from __future__ import annotations

import copy
import re
from collections.abc import Callable, Iterable, Iterator
from pathlib import Path

from docx import Document
from docx.shared import Pt, RGBColor
from docx.table import Table, _Cell
from docx.text.paragraph import Paragraph

from ..errors import AppError
from ..models import QuotationLineItem
from ..parsing.docx_parser import unique_cells
from ..template_analysis import BLANK_RE, PLACEHOLDER_RE
from .common import Resolver, safe_text

_BLANK_SPAN = re.compile(r"_{3,}|\.{4,}|…+")


def replace_spans(paragraph: Paragraph, spans: list[tuple[int, int, str]]) -> None:
    """Replace character spans of the paragraph's run text, keeping the first affected run's formatting."""
    runs = paragraph.runs
    if not runs or not spans:
        return
    offsets: list[int] = []
    pos = 0
    for r in runs:
        offsets.append(pos)
        pos += len(r.text)
    for start, end, replacement in sorted(spans, key=lambda s: s[0], reverse=True):
        i = max(k for k, off in enumerate(offsets) if off <= start)
        j = max(k for k, off in enumerate(offsets) if off < end) if end > start else i
        text_i = runs[i].text
        if i == j:
            runs[i].text = text_i[: start - offsets[i]] + replacement + text_i[end - offsets[i] :]
        else:
            text_j = runs[j].text
            runs[i].text = text_i[: start - offsets[i]] + replacement
            for k in range(i + 1, j):
                runs[k].text = ""
            runs[j].text = text_j[end - offsets[j] :]


def fill_placeholders(paragraph: Paragraph, resolve: Callable[[str], str | None]) -> int:
    full = "".join(r.text for r in paragraph.runs)
    if "{{" not in full:
        return 0
    spans: list[tuple[int, int, str]] = []
    for m in PLACEHOLDER_RE.finditer(full):
        replacement = resolve(m.group(1))
        if replacement is not None:
            spans.append((m.start(), m.end(), replacement))
    replace_spans(paragraph, spans)
    return len(spans)


def set_cell_text(cell: _Cell, text: str) -> None:
    paragraphs = cell.paragraphs
    first = paragraphs[0]
    for extra in paragraphs[1:]:
        extra._p.getparent().remove(extra._p)
    runs = first.runs
    if runs:
        runs[0].text = text
        for r in runs[1:]:
            r.text = ""
    else:
        first.add_run(text)


def _iter_table_paragraphs(table: Table) -> Iterator[Paragraph]:
    for row in table.rows:
        for cell in unique_cells(row):
            yield from cell.paragraphs
            for nested in cell.tables:
                yield from _iter_table_paragraphs(nested)


def _all_paragraphs(document) -> Iterator[Paragraph]:
    for item in document.iter_inner_content():
        if isinstance(item, Paragraph):
            yield item
        elif isinstance(item, Table):
            yield from _iter_table_paragraphs(item)
    seen: list = []  # keep element references: lxml proxies are only stable while referenced
    for section in document.sections:
        parts: Iterable = (
            section.header,
            section.footer,
            section.first_page_header,
            section.first_page_footer,
            section.even_page_header,
            section.even_page_footer,
        )
        for part in parts:
            if part.is_linked_to_previous:
                continue
            element = part._element
            if any(element is s for s in seen):
                continue
            seen.append(element)
            yield from part.paragraphs
            for t in part.tables:
                yield from _iter_table_paragraphs(t)


def _add_draft_banner(document) -> None:
    body_items = list(document.iter_inner_content())
    banner_text = "DRAFT - generated by TenderFlow for internal review. Not for submission."
    if body_items and isinstance(body_items[0], Paragraph):
        para = body_items[0].insert_paragraph_before("")
    else:
        para = document.add_paragraph("")
        if body_items and isinstance(body_items[0], Table):
            body_items[0]._tbl.addprevious(para._p)  # move the new paragraph above the first table
    run = para.add_run(banner_text)
    run.bold = True
    run.font.size = Pt(8)
    run.font.color.rgb = RGBColor(0xA5, 0x53, 0x47)


def export_docx(template_path: Path, out_path: Path, resolver: Resolver, draft: bool) -> list[str]:
    warnings: list[str] = []
    try:
        document = Document(str(template_path))
    except Exception as exc:
        raise AppError("export_failed", "The template could not be opened for export.", 500) from exc

    items_info = resolver.template.items_table
    tables = [item for item in document.iter_inner_content() if isinstance(item, Table)]
    item_row_element = None  # hold a reference so lxml keeps returning the same proxy object
    if items_info is not None and items_info.table_index is not None and items_info.table_index < len(tables):
        t = tables[items_info.table_index]
        if items_info.template_row < len(t.rows):
            item_row_element = t.rows[items_info.template_row]._tr

    # 1) Scalar placeholders everywhere except the repeated items row.
    for paragraph in _all_paragraphs(document):
        tr = paragraph._p.getparent()
        while tr is not None and not tr.tag.endswith("}tr"):
            tr = tr.getparent()
        if item_row_element is not None and tr is item_row_element:
            continue
        fill_placeholders(paragraph, resolver.placeholder_text)

    # 2) "Label: ______" blanks in body paragraphs and label cells followed by an empty cell.
    para_no = 0
    for item in document.iter_inner_content():
        if not isinstance(item, Paragraph):
            continue
        para_no += 1
        fid = f"lbl:paragraph{para_no}"
        if fid not in {tf.id for tf in resolver.template.fields}:
            continue
        text = "".join(r.text for r in item.runs)
        if not BLANK_RE.match(text.strip()):
            continue
        value = resolver.field_text(fid)
        if not value:
            continue
        m = _BLANK_SPAN.search(text)
        if m:
            replace_spans(item, [(m.start(), m.end(), value)])
    for tf in resolver.template.fields:
        m = re.match(r"^lbl:t(\d+)r(\d+)c(\d+)$", tf.id)
        if not m:
            continue
        t_i, r_i, c_i = (int(x) - 1 for x in m.groups())
        if t_i >= len(tables) or r_i >= len(tables[t_i].rows):
            continue
        cells = unique_cells(tables[t_i].rows[r_i])
        if c_i < len(cells):
            value = resolver.field_text(tf.id)
            if value:
                set_cell_text(cells[c_i], value)

    # 3) Line items: clone the template row once per item.
    if items_info is None or items_info.table_index is None or items_info.table_index >= len(tables):
        if resolver.q.line_items:
            warnings.append("The template has no items table, so line items were not written into the document.")
    else:
        table = tables[items_info.table_index]
        rows = table.rows
        if items_info.template_row < len(rows):
            template_tr = rows[items_info.template_row]._tr
        else:
            template_tr = rows[items_info.header_row]._tr
        anchor = template_tr
        col_attrs = resolver.column_attributes()
        for line in resolver.q.line_items:
            new_tr = copy.deepcopy(template_tr)
            anchor.addnext(new_tr)
            anchor = new_tr
            new_row = next(r for r in table.rows if r._tr is new_tr)
            cells = unique_cells(new_row)
            if items_info.mode == "placeholder_row":

                def item_value(key: str, _line: QuotationLineItem = line) -> str | None:
                    if key.lower().startswith("item."):
                        return resolver.item_text(_line, key.split(".", 1)[1].lower())
                    return None

                for cell in cells:
                    for p in cell.paragraphs:
                        fill_placeholders(p, item_value)
            else:
                for idx, cell in enumerate(cells):
                    attr = col_attrs.get(idx)
                    set_cell_text(cell, resolver.item_text(line, attr) if attr else "")
        if items_info.template_row < len(rows):
            template_tr.getparent().remove(template_tr)

    if draft:
        _add_draft_banner(document)
    document.core_properties.comments = "Generated by TenderFlow" + (" (draft)" if draft else "")
    out_path.parent.mkdir(parents=True, exist_ok=True)
    document.save(str(out_path))
    return warnings


def docx_text(path: Path) -> str:
    """All text in a DOCX (body, tables, headers, footers) for post-export verification."""
    document = Document(str(path))
    return "\n".join(safe_text(p.text) for p in _all_paragraphs(document))
