"""Quotation generation and deterministic arithmetic (pipeline stage 6).

Only supplied, extracted or user-confirmed values are used. Money is ``Decimal`` rounded half-up to two
decimal places; a total is only produced when every line amount is known.
"""

from __future__ import annotations

from datetime import date, timedelta
from decimal import ROUND_HALF_UP, Decimal

from .extraction.normalize import duration_days
from .fields import QUOTATION_FIELDS
from .models import (
    REVIEWED_STATUSES,
    AppSettings,
    CompanyProfile,
    ExtractedField,
    FieldStatus,
    Origin,
    Project,
    QField,
    Quotation,
    QuotationLineItem,
    TaxSettings,
    utcnow,
)
from .pricing import describe_match, match_price
from .storage import new_id

MONEY_Q = Decimal("0.01")


def money(value: Decimal) -> Decimal:
    return value.quantize(MONEY_Q, rounding=ROUND_HALF_UP)


def format_money(value: Decimal | None) -> str | None:
    if value is None:
        return None
    return f"{money(value):,.2f}"


def format_quantity(value: Decimal | None) -> str | None:
    if value is None:
        return None
    text = f"{value:f}"
    if "." in text:
        text = text.rstrip("0").rstrip(".")
    return text or "0"


def format_date(d: date) -> str:
    return f"{d.day} {d.strftime('%B %Y')}"


def make_field(
    key: str, value: str | None, origin: Origin, *, confirmed: bool = False, note: str | None = None, source=None
) -> QField:
    label = QUOTATION_FIELDS[key].label if key in QUOTATION_FIELDS else key
    if value is None or (isinstance(value, str) and not value.strip()):
        return QField(key=key, label=label, value=None, origin="missing", note=note)
    return QField(key=key, label=label, value=value, origin=origin, confirmed=confirmed, note=note, source=source)


def _from_extracted(key: str, ef: ExtractedField | None, *, commitment: bool = False) -> QField | None:
    if ef is None or not ef.value:
        return None
    reviewed = ef.status in REVIEWED_STATUSES
    note = None
    if commitment:
        note = "Copied from the tender's requirement. Confirm you can commit to it."
    elif not reviewed:
        note = "Extracted from the tender but not yet confirmed in the review step."
    return make_field(
        key,
        ef.value,
        "user" if ef.status == FieldStatus.edited else "extracted",
        confirmed=reviewed and not commitment,
        note=note,
        source=ef.sources[0] if ef.sources else None,
    )


def build_quotation(
    project: Project, settings: AppSettings, company: CompanyProfile, today: date | None = None
) -> Quotation:
    today = today or date.today()
    ext = {f.key: f for f in (project.extraction.fields if project.extraction else [])}
    fields: dict[str, QField] = {}

    # Company header: only what the user entered in Settings (or edited for this project).
    for key, attr in [
        ("company_name", "name"),
        ("company_address", "address"),
        ("company_phone", "phone"),
        ("company_email", "email"),
        ("company_registration", "registration"),
        ("prepared_by", "prepared_by"),
    ]:
        fields[key] = make_field(key, getattr(company, attr), "company_profile", confirmed=True)

    # Quotation details generated by TenderFlow (clearly labelled as calculated).
    prefix = (settings.quotation_prefix or "QTN").strip()[:12] or "QTN"
    fields["quotation_title"] = make_field(
        "quotation_title",
        "Quotation",
        "calculated",
        confirmed=True,
        note="Default title. Change it if your template uses another title.",
    )
    fields["quotation_number"] = make_field(
        "quotation_number",
        f"{prefix}-{today:%Y%m%d}-{project.id[-4:].upper()}",
        "calculated",
        confirmed=True,
        note="Generated by TenderFlow. Replace it with your own numbering if needed.",
    )
    fields["quotation_date"] = make_field(
        "quotation_date", format_date(today), "calculated", confirmed=True, note="Date the draft was generated."
    )

    # Buyer / tender information extracted from the tender.
    for key, src in [
        ("buyer_name", "issuer_name"),
        ("buyer_address", "issuer_address"),
        ("tender_reference", "tender_reference"),
        ("tender_title", "tender_title"),
        ("submission_deadline", "submission_deadline"),
    ]:
        fields[key] = _from_extracted(key, ext.get(src)) or make_field(key, None, "missing")

    # Commercial terms: the tender's stated requirement is proposed (needs confirmation), otherwise the
    # company's own default terms from Settings, otherwise missing.
    for key, src, default_attr in [
        ("delivery_terms", "delivery_period", "default_delivery_terms"),
        ("payment_terms", "payment_terms", "default_payment_terms"),
        ("warranty_terms", "warranty", "default_warranty_terms"),
        ("validity_terms", "bid_validity", "default_validity_terms"),
    ]:
        qf = _from_extracted(key, ext.get(src), commitment=True)
        if qf is None:
            qf = make_field(key, getattr(company, default_attr), "company_profile", confirmed=True)
        fields[key] = qf
    fields["notes"] = make_field("notes", None, "missing")

    q = Quotation(id=new_id("rec"), fields=fields)

    # Currency: only an explicit choice from Settings. The tender's currency is a suggestion (validation).
    if settings.default_currency:
        q.currency = settings.default_currency
        q.currency_origin = "settings"
    # Tax: only what the user configured. No rate is ever assumed.
    q.tax = TaxSettings.model_validate(settings.tax.model_dump())
    q.tax_origin = "settings"

    # Line items from the reviewed extraction, prices only from the user's price list.
    if project.extraction:
        for ext_item in project.extraction.line_items:
            if not ext_item.description and ext_item.quantity is None:
                continue
            reviewed = ext_item.status in REVIEWED_STATUSES
            origin_ext: Origin = "user" if ext_item.status == FieldStatus.edited else "extracted"
            item = QuotationLineItem(
                id=new_id("itm"),
                item_no="",
                description=ext_item.description,
                specification=ext_item.specification,
                quantity=ext_item.quantity,
                unit=ext_item.unit,
                source=ext_item.source,
                tender_line_id=ext_item.id,
                tender_quantity=ext_item.quantity,
                reviewed=reviewed,
                origins={
                    "description": origin_ext if ext_item.description else "missing",
                    "specification": origin_ext if ext_item.specification else "missing",
                    "quantity": origin_ext if ext_item.quantity is not None else "missing",
                    "unit": origin_ext if ext_item.unit else "missing",
                    "unit_price": "missing",
                },
            )
            match = match_price(ext_item.description, project.price_list)
            if match is not None:
                item.unit_price = match.row.unit_price
                item.origins["unit_price"] = "price_list"
                item.price_note = describe_match(match)
                item.price_confirmed = match.exact
            q.line_items.append(item)

    update_validity_date(q, project)
    recalculate(q)
    return q


def update_validity_date(q: Quotation, project: Project) -> None:
    """valid_until = base date + validity period, when both are known. Otherwise it stays missing."""
    validity = q.fields.get("validity_terms")
    days = duration_days(validity.value) if validity and validity.value else None
    if days is None:
        q.fields["valid_until"] = make_field(
            "valid_until", None, "missing", note="Set a validity period (e.g. “90 days”) to calculate this date."
        )
        return
    base: date | None = None
    basis = "the quotation date"
    text = (validity.value or "").lower() if validity else ""
    if "opening" in text and project.extraction:
        opening = next((f for f in project.extraction.fields if f.key == "bid_opening"), None)
        if opening and opening.normalized:
            try:
                base = date.fromisoformat(opening.normalized[:10])
                basis = f"bid opening ({format_date(base)})"
            except ValueError:
                base = None
    if base is None:
        base = q.generated_at.date()
    target = base + timedelta(days=days)
    q.fields["valid_until"] = make_field(
        "valid_until", format_date(target), "calculated", confirmed=True, note=f"{days} days from {basis}."
    )


def recalculate(q: Quotation) -> Quotation:
    for i, item in enumerate(q.line_items, start=1):
        item.item_no = str(i)
        calc = (
            money(item.quantity * item.unit_price)
            if item.quantity is not None and item.unit_price is not None
            else None
        )
        if item.amount_override is not None:
            item.amount = money(item.amount_override)
            item.origins["amount"] = "user"
        else:
            item.amount = calc
            item.origins["amount"] = "calculated" if calc is not None else "missing"
    amounts = [it.amount for it in q.line_items]
    if q.line_items and all(a is not None for a in amounts):
        q.subtotal = money(sum((a for a in amounts if a is not None), Decimal("0")))
    else:
        q.subtotal = None
    if q.tax.enabled:
        if q.subtotal is not None and q.tax.rate is not None:
            q.tax_amount = money(q.subtotal * q.tax.rate / Decimal("100"))
        else:
            q.tax_amount = None
    else:
        q.tax_amount = None
    if q.subtotal is None:
        q.total = None
    elif q.tax.enabled:
        q.total = money(q.subtotal + q.tax_amount) if q.tax_amount is not None else None
    else:
        q.total = q.subtotal
    _refresh_derived_fields(q)
    q.updated_at = utcnow()
    return q


def _refresh_derived_fields(q: Quotation) -> None:
    f = q.fields
    f["currency"] = make_field(
        "currency", q.currency, q.currency_origin if q.currency else "missing", confirmed=bool(q.currency)
    )
    f["subtotal"] = make_field(
        "subtotal",
        format_money(q.subtotal),
        "calculated",
        confirmed=True,
        note=None if q.subtotal is not None else "Waiting for all line amounts.",
    )
    if q.tax.enabled:
        label = (q.tax.label or "Tax").strip()
        rate_text = f"{format_quantity(q.tax.rate)}%" if q.tax.rate is not None else None
        f["tax_label"] = make_field(
            "tax_label", f"{label} ({rate_text})" if rate_text else label, q.tax_origin, confirmed=True
        )
        f["tax_rate"] = make_field("tax_rate", rate_text, q.tax_origin, confirmed=True)
        f["tax_amount"] = make_field(
            "tax_amount",
            format_money(q.tax_amount),
            "calculated",
            confirmed=True,
            note=None if q.tax_amount is not None else "Needs a tax rate and a subtotal.",
        )
    else:
        f["tax_label"] = make_field("tax_label", "Tax", "calculated", confirmed=True)
        f["tax_rate"] = make_field("tax_rate", "Not applied", "calculated", confirmed=True)
        f["tax_amount"] = make_field(
            "tax_amount",
            "Not applied",
            "calculated",
            confirmed=True,
            note="No tax configured. TenderFlow never assumes a tax rate.",
        )
    f["total"] = make_field(
        "total",
        format_money(q.total),
        "calculated",
        confirmed=True,
        note=None if q.total is not None else "Waiting for all line amounts.",
    )


def item_display(item: QuotationLineItem, attribute: str) -> str | None:
    if attribute == "item_no":
        return item.item_no
    if attribute in ("quantity",):
        return format_quantity(item.quantity)
    if attribute in ("unit_price", "amount"):
        return format_money(getattr(item, attribute))
    value = getattr(item, attribute, None)
    return str(value) if value is not None else None
